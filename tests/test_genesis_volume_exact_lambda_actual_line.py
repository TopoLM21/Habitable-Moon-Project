def _native(shape, values):
    pairs = []
    for value in values:
        fraction = Fraction(value)
        pairs.append([str(fraction.numerator), str(fraction.denominator)])
    return dict(shape=shape, numerator_denominator=pairs)


def _witness():
    # An explicit two-component archive isolates alias/authentication behavior.
    # It is not generated by a polynomial producer or presented as an integral.
    value = dict(component_names=["projected.stiffness_enriched[0,0]"], values=[4.],
        roundoff_component_bounds=[.125], absolute_operand_scales=[4.],
        blocks={}, block_roundoff_component_bounds={},
        projected_blocks={"stiffness_enriched": [[4.]]},
        projected_roundoff_component_bounds={"stiffness_enriched": [[.125]]},
        coefficients={"w": [2., 1.], "memoryhat": [[.5, -.25], [0., 0.]]},
        coefficient_roundoff_bounds={"w": [0., 0.], "memoryhat": [[0., 0.], [0., 0.]]},
        probe_contractions={}, interval={"lambda_mid": .5})
    value["native_exact_binary_ratio"] = {
        "values": _native([1], [4]), "budgets": _native([1], [.125]),
        "own": _native([1], [4]), "projected.stiffness_enriched": _native([1, 1], [4]),
        "projectedbudget.stiffness_enriched": _native([1, 1], [.125]),
        "coefficient.w": _native([2], [2, 1]), "coefficient_bound.w": _native([2], [0, 0]),
        "coefficient.memoryhat": _native([2, 2], [.5, -.25, 0, 0]),
        "coefficient_bound.memoryhat": _native([2, 2], [0, 0, 0, 0]),
        "interval.lambda_mid": _native([], [.5])}
    return audit.seal(value, "archive_sha256")


def test_cli_imports_no_source_extractor_or_operator_producer():
    command = [sys.executable, "-c", "import json,sys; from analysis.genesis_volume_exact_lambda_validation import actual_line_audit; print(json.dumps(sorted(sys.modules)))"]
    result = subprocess.run(command, cwd=audit.ROOT, env=os.environ.copy(),
                            text=True, capture_output=True, check=True)
    modules = set(json.loads(result.stdout))
    assert not any(name.startswith("tectonics") for name in modules)
    assert "analysis.genesis_volume_exact_lambda_validation.source_control" not in modules
    assert "analysis.genesis_volume_exact_lambda_validation.actual_control" not in modules
    assert "analysis.genesis_volume_clipped_validation.actual_control" not in modules


def test_valid_reseal_does_not_hide_public_native_alias_corruption():
    witness = _witness()
    assert audit._alias_checks(witness)["status"] == "PASS"
    witness["coefficients"]["w"][0] = 3.
    witness = audit.seal(witness, "archive_sha256")
    audit.checked(witness, "archive_sha256")
    with pytest.raises(ValueError, match="terminal conversion"):
        audit._alias_checks(witness)


def test_consistent_public_native_projection_still_requires_flat_alias():
    witness = _witness()
    witness["projected_blocks"]["stiffness_enriched"][0][0] = 8.
    witness["native_exact_binary_ratio"]["projected.stiffness_enriched"] = _native([1, 1], [8])
    witness = audit.seal(witness, "archive_sha256")
    with pytest.raises(ValueError, match="Flattened/direct native component values"):
        audit._alias_checks(witness)


@pytest.mark.parametrize("field", ["w", "memoryhat"])
def test_source_coefficient_negatives_reseal_and_preserve_all_aliases(field):
    witness = _witness()
    original = deepcopy(witness)
    changed, mutation = audit._coefficient_negative(witness, field)
    assert witness == original
    assert changed["archive_sha256"] != witness["archive_sha256"]
    audit.checked(changed, "archive_sha256")
    assert audit._alias_checks(changed)["status"] == "PASS"
    assert Fraction(mutation["changed_exact_ratio"]) != Fraction(mutation["original_exact_ratio"])
    assert changed["values"] == witness["values"]


def _check(error, *, passed=False):
    return dict(absolute_difference=str(error), arithmetic_bound="0.125", passed=passed)


def test_existing_open_without_targeted_error_growth_is_not_detected_negative():
    original = _witness()
    changed, mutation = audit._projected_negative(original)
    name = mutation["component_name"]
    before = {"all_component_checks": {name: _check(20)}, "source_direct_quadrature_status": "OPEN"}
    after = {"all_component_checks": {name: _check(21)}, "source_direct_quadrature_status": "OPEN"}
    record = audit._negative_record("projection", changed, mutation, after, before)
    assert record["valid_resealed_archive_body"] is True
    assert record["native_public_alias_checks"]["status"] == "PASS"
    assert record["status"] == "OPEN"
    assert record["targeted_independent_mathematical_detection"] is False


def test_exact_targeted_projection_difference_is_detected_with_cached_baseline():
    original = _witness()
    changed, mutation = audit._projected_negative(original)
    name = mutation["component_name"]
    before = {"all_component_checks": {name: _check(0, passed=True)}}
    delta = Fraction(mutation["changed_exact_ratio"]) - Fraction(mutation["original_exact_ratio"])
    after = {"all_component_checks": {name: _check(delta)}}
    record = audit._negative_record("projection", changed, mutation, after, before)
    assert record["status"] == "DETECTED"
    assert record["targeted_independent_mathematical_detection"] is True
    assert changed["values"][0] == 8.
    assert original["values"][0] == 4.


def test_alternate_preliminary_fixture_is_refused_before_any_numerical_work():
    with tempfile.TemporaryDirectory(prefix="exact_line_fixture_unit_", dir="/workspace") as temporary:
        temporary = Path(temporary)
        output = temporary / "report.json"
        directory = temporary / "control"
        directory.mkdir()
        preliminary = temporary / "preliminary.json"
        for path, seconds in ((preliminary, 1.), (directory / "source_fixture.json", 2.)):
            fixture = audit.seal(dict(extraction_seconds=seconds), "source_fixture_sha256")
            path.write_bytes(audit.canonical(fixture) + b"\n")
        with pytest.raises(ValueError, match="exact actual-control source copy"):
            audit.run(preliminary, directory, output)
        assert not output.exists()


def _mock_control(monkeypatch, *, refused_radii):
    """Isolate report control flow from source authentication and all numerics."""
    observed = []
    flags = dict(physical_creation_admitted=False, physical_release_admitted=False,
                 available_for_creation_funding=False, automated_goal_enabled=False,
                 physical_contraction_certified=False, angular_accuracy_certified=False)
    fixture = dict(previous_source_count=434, previous_source_sha256={f"fake_{i}.py": "0" * 64 for i in range(434)},
        cohort_count=800, accepted_interval_count=4, source_pins={}, original_minimal_source_pins=[],
        compact_comparison_archive_pin=dict(path="/workspace/isolated_mock_anchor", bytes=0, raw_sha256="0" * 64),
        history_reinitialized=False, accepted_planet_memory_changed=False, cases=[], **flags)
    for cohort in (1, 41, 80):
        supports = {}
        for name, radius in ([('fixed_100m_clipped_support', 100.), ('original_radius_baseline', 4.)]
                             if cohort == 1 else [('fixed_100m_clipped_support', 100.)]):
            supports[name] = audit.seal(dict(seed_center_world_m=[0., 0., 0.], seed_radius_m=radius,
                original_declared_added_basis=None, original_declared_parent_basis=None,
                declared_probes=[]), "support_sha256")
        fixture['cases'].append(audit.seal(dict(original_cohort_id=cohort,
            source_inputs=dict(cohort=cohort), supports=supports), "source_case_sha256"))
    fixture = audit.seal(fixture, "source_fixture_sha256")
    controls = {}
    for index, case in enumerate(fixture['cases']):
        for name, support in case['supports'].items():
            witness = _witness()
            witness['source_binding_sha256'] = 'isolated_mock_source'
            witness['native_exact_binary_ratio']['interval.barycentric'] = _native([3], [Fraction(1, 3)] * 3)
            witness = audit.seal(witness, 'archive_sha256')
            controls[f'case_{index:03d}_{name}.json'] = audit.seal(dict(cohort_id=case['original_cohort_id'],
                support=name, source_case_sha256=case['source_case_sha256'],
                source_support_sha256=support['support_sha256'], source_fixture_sha256=fixture['source_fixture_sha256'],
                original_computational_support=support, source=dict(source_binding_sha256='isolated_mock_source'),
                line_witness=witness, line_witness_barycentric_exact_binary_ratios=['1/3'] * 3,
                source_history_reinitialized=False, accepted_planet_memory_changed=False,
                angular_control=dict(status='OPEN', reason='isolated report-flow test'), **flags), 'support_report_sha256')
    constant_pin = dict(bytes=0, raw_sha256='0' * 64)

    def remember(inputs, path, expected=None):
        inputs[str(Path(path).resolve())] = dict(constant_pin)
        return dict(constant_pin)

    def read(path, key, inputs, **options):
        remember(inputs, path)
        return fixture if Path(path).name == 'source_fixture.json' else controls[Path(path).name]

    def integrate(raw, N, **options):
        observed.append((raw['cohort'], raw['seed_radius_m']))
        if raw['seed_radius_m'] in refused_radii:
            error = audit.independent.IndependentLineRefusal('isolated unresolved quadrature observation')
            error.diagnostics = dict(format='independent-quadrature-refusal-observation-0.1', status='REFUSED',
                precision_decimal_digits=80, quadrature_orders=[12, 20], component_names=['test.component'],
                oracle_input_binding_sha256='untrusted-observation-binding',
                coarse_observed_values=['1.0'], fine_observed_values=['2.0'], failed_component_count=1,
                failed_component_checks={'test.component': {'absolute_difference': '1.0', 'arithmetic_bound': '1e-70'}},
                **flags)
            raise error
        return dict(precision_decimal_digits=80, status='ISOLATED_TRUSTED_RESULT',
                    oracle_input_binding_sha256='isolated-success-binding', **flags)

    def fields(raw, N, witness, **options):
        checks = {}
        for name, error in [('xi=0.0.w()', abs(witness['coefficients']['w'][0] - 2.)),
                            ('xi=0.0.memoryhat(0,)', abs(witness['coefficients']['memoryhat'][0][0] - .5))]:
            checks[name] = _check(error, passed=error <= .125)
        return dict(coefficient_source_status='PASS' if all(row['passed'] for row in checks.values()) else 'OPEN',
                    checks=checks, **flags)

    def primitive(*args, **options):
        return dict(represented_polynomial_primitive_status='PASS', component_checks={}, **flags)

    def arithmetic(raw, N, witness, *, oracle, **options):
        assert raw['seed_radius_m'] not in refused_radii, 'Refused observation was passed as trusted oracle'
        assert oracle['status'] == 'ISOLATED_TRUSTED_RESULT'
        name = witness['component_names'][0]
        error = abs(witness['values'][0] - 4.)
        return dict(source_direct_quadrature_status='PASS' if error <= .125 else 'OPEN',
            all_component_checks={name: _check(error, passed=error <= .125)},
            mismatching_components=[] if error <= .125 else [name], geometry_status='PASS', geometry_checks={},
            represented_polynomial_primitive_audit=primitive(), **flags)

    monkeypatch.setattr(audit, 'pin', lambda path: dict(constant_pin))
    monkeypatch.setattr(audit, '_remember', remember)
    monkeypatch.setattr(audit, '_read', read)
    monkeypatch.setattr(audit, '_source_archive_checks', lambda *args: {'status': 'PASS'})
    monkeypatch.setattr(audit, '_alias_checks', lambda *args: {'status': 'PASS'})
    monkeypatch.setattr(audit.independent, 'integrate_source_line', integrate)
    monkeypatch.setattr(audit.independent, 'audit_coefficient_fields', fields)
    monkeypatch.setattr(audit.independent, 'audit_represented_primitive', primitive)
    monkeypatch.setattr(audit.independent, 'audit_geometry_witness',
                        lambda *args, **kwargs: dict(geometry_status='PASS', geometry_checks={}, **flags))
    monkeypatch.setattr(audit.independent, 'audit_line_witness', arithmetic)
    return observed


@pytest.mark.parametrize('refused_radii,expected_refusals,expected_negatives', [({4.}, 1, 3), ({4., 100.}, 4, 0)])
def test_refused_quadrature_retains_all_lines_and_false_gates(monkeypatch, refused_radii, expected_refusals, expected_negatives):
    observed = _mock_control(monkeypatch, refused_radii=refused_radii)
    with tempfile.TemporaryDirectory(prefix='exact_line_refusal_unit_', dir='/workspace') as temporary:
        directory = Path(temporary)
        report_path = directory / 'report.json'
        report = audit.run(directory / 'source_fixture.json', directory, report_path)
        audit.checked(json.loads(report_path.read_bytes()), 'report_sha256')
    assert observed == [(1, 100.), (1, 4.), (41, 100.), (80, 100.)]
    assert report['selected_original_line_count'] == len(report['cases']) == 4
    assert report['status'] == report['selected_line_direct_quadrature_status'] == 'OPEN'
    assert report['source_quadrature_refusal_count'] == expected_refusals
    assert report['mathematical_negative_count'] == expected_negatives
    assert report['selected_line_represented_polynomial_primitive_status'] == 'PASS'
    assert report['refused_observations_used_as_trusted_oracle'] is False
    for row in report['cases']:
        if row['source_quadrature_refused']:
            assert row['trusted_oracle_available'] is False
            assert row['selected_line_component_arithmetic_status'] == 'OPEN'
            assert row['selected_line_arithmetic_audit']['fixed_line_numeric_agreement_status'] == 'NOT_EVALUATED'
            assert row['source_field_audit']['coefficient_source_status'] == 'PASS'
            diagnostic = row['source_quadrature_refusal']['diagnostic_archive']
            audit.checked(diagnostic, 'sha256')
            assert diagnostic['status'] == 'REFUSED'
            assert diagnostic['coarse_observed_values'] == ['1.0']
            assert diagnostic['fine_observed_values'] == ['2.0']
            assert row['source_quadrature_refusal']['unresolved_observations_used_as_trusted_oracle'] is False
    for key in ('physical_creation_admitted', 'physical_release_admitted', 'available_for_creation_funding',
                'automated_goal_enabled', 'physical_contraction_certified', 'angular_accuracy_certified',
                'source_history_reinitialized', 'accepted_planet_memory_changed', 'point_one_complete'):
        assert report[key] is False
    if expected_negatives:
        assert report['resealed_mathematical_negative_status'] == 'PASS'
        assert {row['authentic_source_control_filename'] for row in report['genuine_resealed_mathematical_negatives']} == {
            'case_000_fixed_100m_clipped_support.json'}
